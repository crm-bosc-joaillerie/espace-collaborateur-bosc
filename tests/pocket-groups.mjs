import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import ts from 'typescript';
const helper=readFileSync(new URL('../lib/pocket-groups.ts',import.meta.url),'utf8');
const js=ts.transpileModule(helper,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ESNext}}).outputText;
const {groupCollaboratorPockets,pocketWrites}=await import('data:text/javascript;base64,'+Buffer.from(js).toString('base64'));
const rows=[20,40,40].map((minutes,index)=>({no:'4803',client:'Client',piece:'Pièce '+index,duree:'0 h '+minutes+' min',etat:index?'En cours':'Fait',livraison:'2026-11-12',monthKey:index===2?'2026-12':'2026-11',weekKey:'S46',data:{interventionId:'work'+index,montant:index?100:60,note:'Note '+index},_crmId:'id'+index,record_key:'key'+index}));
const snapshot=JSON.stringify(rows);
const groups=groupCollaboratorPockets(rows);
assert.equal(groups.length,1);
assert.equal(groups[0].duree,'1 h 40 min');
assert.equal(groups[0].etat,'En cours');
assert.equal(groupCollaboratorPockets(groups).length,1);
assert.equal(groupCollaboratorPockets(groups)[0].duree,'1 h 40 min','Regrouping must not double-count totals');
assert.equal(groupCollaboratorPockets(groups,row=>row.monthKey==='2026-12')[0].duree,'1 h 40 min');
assert.equal(groupCollaboratorPockets(groups,row=>row.monthKey==='2026-12')[0].monthKey,'2026-12');
const input={no:groups[0].no,client:groups[0].client,piece:groups[0].piece,etat:groups[0].etat,livraison:groups[0].livraison,note:'Note 0'};
const writes=pocketWrites(groups[0],input);
assert.deepEqual(writes.map(row=>row._crmId),['id0','id1','id2']);
assert.deepEqual(writes.map(row=>row.interventionId),['work0','work1','work2']);
assert.deepEqual(writes.map(row=>row.piece),rows.map(row=>row.piece));
assert.deepEqual(writes.map(row=>row.etat),rows.map(row=>row.etat));
assert.deepEqual(writes.map(row=>row.note),rows.map(row=>row.data.note));
assert(pocketWrites(groups[0],{...input,etat:'Fait'}).every(row=>row.etat==='Fait'));
assert(pocketWrites(groups[0],{...input,piece:'Nouvelle désignation'}).every(row=>row.piece==='Nouvelle désignation'));
assert.equal(JSON.stringify(rows),snapshot);
const page=readFileSync(new URL('../app/page.tsx',import.meta.url),'utf8');
const source=page.slice(page.indexOf('function activeCollaboratorWork('),page.indexOf('function Pochettes('));
const plain=source.replace('planningRows:PlanningRow[], pochettesRows:PochettesRow[]','planningRows, pochettesRows').replace('(status:string)','(status)');
const active=new Function('groupCollaboratorPockets','planning','pochettes',plain+';return activeCollaboratorWork(planning,pochettes)');
const planning=rows.map(row=>({...row,pochette:row.no,statut:row.etat}));
assert.equal(active(groupCollaboratorPockets,planning,rows).pochettes.length,1,'A partially completed pocket stays visible');
assert.equal(active(groupCollaboratorPockets,planning,rows.map(row=>({...row,etat:'Fait'}))).planning.length,0,'A fully completed pocket is hidden');
assert.equal(groupCollaboratorPockets([{no:'',duree:'—'},{no:'',duree:'—'}]).length,2);
console.log('Collaborateur : une carte par pochette, durées, filtres, statut global et écritures individuelles validés.');
